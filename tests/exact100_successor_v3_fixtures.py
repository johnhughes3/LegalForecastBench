"""Shared synthetic fixtures for the v3 exact-100 successor lane tests.

Every value here is invented: no production case, document, digest, or
filesystem path appears, and nothing reads the artifacts tree.  The packets are
hand-authored (``synthetic: true``) and generated by the builders below.
"""

