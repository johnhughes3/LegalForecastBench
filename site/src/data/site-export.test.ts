import assert from "node:assert/strict";
import test from "node:test";
import fixture from "./fixtures/site-export.json" with { type: "json" };
import { parseSiteExport } from "./site-export.js";

test("accepts the export generated by the Python scorer and exporter", () => {
	const value: unknown = structuredClone(fixture);
	const parsed = parseSiteExport(value);
	assert.equal(parsed, value);
	assert.ok(parsed.results.length > 0);
	assert.ok(parsed.results[0]?.units.length);
});

test("rejects missing and unsupported contract versions", () => {
	const { schema_version: _version, ...unversioned } = fixture;
	assert.throws(() => parseSiteExport(unversioned), /schema_version/);
	assert.throws(
		() => parseSiteExport({ ...fixture, schema_version: "future-version" }),
		/schema_version/,
	);
});

test("rejects accidental raw fields at the public boundary", () => {
	assert.throws(
		() => parseSiteExport({ ...fixture, raw_response: "private input" }),
		/additional properties/,
	);
});

test("does not coerce scores and rejects probabilities outside their range", () => {
	const parsed = parseSiteExport(fixture);
	const result = parsed.results[0];
	assert.ok(result);
	assert.throws(
		() =>
			parseSiteExport({
				...parsed,
				results: [{ ...result, micro_brier: "0.1" }],
			}),
		/micro_brier must be number/,
	);
	assert.throws(
		() =>
			parseSiteExport({
				...parsed,
				results: [
					{
						...result,
						units: result.units.map((unit) => ({
							...unit,
							probability_fully_dismissed: 1.1,
						})),
					},
				],
			}),
		/probability_fully_dismissed must be <= 1/,
	);
});

test("checks calendar dates used for eligibility", () => {
	assert.throws(
		() =>
			parseSiteExport({
				...fixture,
				contamination_boundary: "2026-02-30",
			}),
		/must match format "date"/,
	);
});
